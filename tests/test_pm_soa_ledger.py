    def test_post_holds_database_lock_until_commit_and_payment_retry_is_once(self):
        import hashlib
        from app.program_billing import lease_soa_posting
        data=self.posting_form('payment')
        with self.app.test_request_context():
            nonce=lease_soa_posting.signer().loads(data['posting_key'])[4]
        key=int.from_bytes(hashlib.sha256(('PMPOST:'+nonce+':').encode()).digest()[:8],'big',signed=True)
        original=lease_soa_posting.ledger_model
        def while_locked():
            with self.engine.connect() as other:
                self.assertFalse(other.execute(text('SELECT pg_try_advisory_xact_lock(:key)'),{'key':key}).scalar())
                other.rollback()
            return original()
        with patch.object(lease_soa_posting,'ledger_model',side_effect=while_locked):
            self.assertEqual(self.submit(data).status_code,302)
        with self.engine.connect() as other:
            self.assertTrue(other.execute(text('SELECT pg_try_advisory_xact_lock(:key)'),{'key':key}).scalar())
            other.rollback()
        self.assertEqual(self.submit(data).status_code,302)
        self.assertEqual(self.session.execute(text('SELECT count(*) FROM bil_tenant_ledger')).scalar(),1)
        self.assertEqual(str(self.session.execute(text('SELECT amount FROM bil_tenant_ledger')).scalar()),'-100.10')

