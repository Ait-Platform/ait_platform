    def test_monthly_uniqueness_under_concurrent_postgresql_transactions(self):
        # Clone only migrated fixture structure into validated random local names.
        from app.program_billing import lease_soa_posting as posting
        self.schedule()
        name='pm_rent_test_'+uuid.uuid4().hex
        self.assertRegex(name,r'^pm_rent_test_[a-f0-9]{32}$')
        table='public.'+name;sequence=table+'_seq'
        self.session.commit()
        self.conn.execute(text('CREATE TABLE '+table+' (LIKE bil_tenant_ledger INCLUDING ALL)'))
        self.conn.execute(text('CREATE SEQUENCE '+sequence+' MINVALUE 1 MAXVALUE 9999 NO CYCLE'));self.conn.commit()
        engine=create_engine(self.engine.url)
        sessions=scoped_session(sessionmaker(bind=engine))
        worker_db=type('WorkerDB',(),{'session':sessions})()
        barrier=threading.Barrier(2)
        def run(_):
            try:
                barrier.wait(timeout=10)
                ref=posting.next_reference('debit')
                sessions.execute(text('INSERT INTO '+table+"""(tenant_id,txn_date,month,description,kind,amount,ref,rent_schedule_id,rent_property_id)
                    VALUES(11,'2026-10-01','2026-10','Rent Due','charge',35000,:ref,1,26)"""),dict(ref=ref))
                sessions.commit();return True
            except IntegrityError:
                sessions.rollback();return False
            finally:sessions.remove()
        try:
            with patch.object(posting,'db',worker_db),patch.dict(posting.REFERENCE_SEQUENCES,{'D':sequence}):
                with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool:
                    self.assertEqual(sorted(pool.map(run,[1,2])),[False,True])
            with engine.connect() as c:self.assertEqual(c.execute(text('SELECT count(*) FROM '+table)).scalar(),1)
        finally:
            sessions.remove();engine.dispose()
            self.conn.execute(text('DROP TABLE '+table));self.conn.execute(text('DROP SEQUENCE '+sequence));self.conn.commit()

