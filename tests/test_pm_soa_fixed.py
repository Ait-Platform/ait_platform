    def test_failed_month_rolls_back_and_is_caught_up_on_retry(self):
        from app.program_billing import lease_soa_posting as posting
        from sqlalchemy.exc import SQLAlchemyError
        self.schedule(start_date='2026-10-01')
        append=posting.append_entry
        def fail_after_insert(*args,**kwargs):
            append(*args,**kwargs)
            raise SQLAlchemyError('Synthetic monthly failure')
        with patch.object(posting,'append_entry',side_effect=fail_after_insert):
            self.assertEqual(self.run_due(),dict(posted=0,failed=1))
