    def test_persistent_idempotency_and_changed_retry_preserves_input(self):
        data=self.posting_form()
        self.assertEqual(self.submit(data).status_code,302)
        # A fresh request/session form cache is not needed: persisted metadata governs retries.
        self.session.expire_all()
        self.assertEqual(self.submit(data).status_code,302)
        self.assertEqual(self.session.execute(text('SELECT count(*) FROM bil_tenant_ledger')).scalar(),1)
        conflict=self.submit(dict(data,amount='101.10'))
