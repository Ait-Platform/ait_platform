def apply_fixed(connection):
    path=Path(__file__).resolve().parents[1]/'migrations/versions/pm_soa_003_fixed_rent.py'
    spec=importlib.util.spec_from_file_location('pm_fixed_migration',path)
    module=importlib.util.module_from_spec(spec);spec.loader.exec_module(module)
    with patch.object(module,'op',Operations(MigrationContext.configure(connection))):module.upgrade()


