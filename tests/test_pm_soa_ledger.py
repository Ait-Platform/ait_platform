def apply_posting_migration(connection):
    path=Path(__file__).resolve().parents[1]/'migrations/versions/pm_soa_001_posting_references.py'
    spec=importlib.util.spec_from_file_location('pm_posting_migration',path)
    module=importlib.util.module_from_spec(spec);spec.loader.exec_module(module)
    with patch.object(module,'op',Operations(MigrationContext.configure(connection))):
        module.upgrade()

