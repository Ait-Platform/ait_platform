    def test_legacy_mismatched_ownership_cannot_contaminate_reports(self):
        own = self.account('Own income', 'income')
        foreign = self.account('Hidden other account', owner=self.other_id)
        for uid, aid, cents in [(self.user_id, own, 1234), (self.other_id, own, 9900), (self.user_id, foreign, 8800)]:
            self.session.execute(sa.text("INSERT INTO bud_ledger(user_id,account_id,txn_date,amount_cents) VALUES (:u,:a,'2026-11-01',:v)"), {'u': uid, 'a': aid, 'v': cents})
        self.session.execute(sa.text("INSERT INTO bud_snapshot(user_id,account_id,as_at,balance_cents) VALUES (:u,:a,'2026-11-30',8800)"), {'u': self.user_id, 'a': foreign})
        self.session.commit()
        ledger = self.client.get('/budget/ledger')
        self.assertNotIn('Hidden other account', ledger.text)
        report = self.client.get('/budget/reports/statement?period=2026-11')
        self.assertIn('12.34', report.text)
        self.assertNotIn('99.00', report.text)
        self.assertNotIn('88.00', report.text)
        self.assertNotIn('Hidden other account', self.client.get('/budget/snapshots').text)

