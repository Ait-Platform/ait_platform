        for url in (self.readings_url,self.statements_url):
            page=self.client.get(url,headers=self.headers);self.assertEqual(page.status_code,200,page.text);self.assertNotIn('PRIVATE',page.text)
            self.assertEqual(self.client.get(url.replace('/26/','/28/'),headers=self.headers).status_code,403)
