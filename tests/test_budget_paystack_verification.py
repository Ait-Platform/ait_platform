    def paystack_tx(self, reference='ref-bc-1', subject='budget_topup', email='tester@example.com', amount=10000, tokens=100, status='success'):
        metadata = dict(email=email, subject=subject, tokens_purchased=tokens)
        with self.app.app_context():
            metadata['order_token'] = security.signed_order(reference, email, subject, amount, 'ZAR', tokens)
        return {
            'reference': reference,
            'status': status,
            'amount': amount,
            'currency': 'ZAR',
            'domain': 'test',
            'metadata': metadata,
            'customer': {'email': email},
        }

    def mock_paystack_response(self, tx):
        m = Mock()
        m.status_code = 200
        m.raise_for_status = Mock()
        m.json = Mock(return_value={'status': True, 'data': deepcopy(tx)})
        return m

    def test_budget_token_topup_payment_and_wallet_credit(self):
        """Verify successful Paystack token top-up allocates tokens to user wallet atomically."""
        tx = self.paystack_tx(reference='ref-topup-1', subject='budget_topup', tokens=100)
        with self.app.app_context():
            with patch('app.payments.paystack.db', SimpleNamespace(session=self.sessions)):
                with patch('app.payments.paystack.User', self.User):
                    with patch('app.payments.paystack.PaystackPayment', self.Payment):
                        with patch('app.models.auth.AitTokenWallet', self.Wallet):
                            with patch('app.models.auth.AitTokenTransaction', self.TokenTxn):
                                with patch('requests.get', return_value=self.mock_paystack_response(tx)):
                                    success = paystack_module.fulfill_order('tester@example.com', 'budget_topup', tx)
                                    self.assertTrue(success)

        # Verify wallet credited by 100 tokens (100 -> 200)
        wallet = self.sessions.query(self.Wallet).filter_by(user_id=101).one()
        self.assertEqual(wallet.balance, 200)

        # Verify AitTokenTransaction audit record
        tt = self.sessions.query(self.TokenTxn).filter_by(wallet_id=wallet.id).one()
        self.assertEqual(tt.amount, 100)
        self.assertIn("Budget", tt.description)

        # Verify PaystackPayment audit record
        pay = self.sessions.query(self.Payment).filter_by(gateway_reference='ref-topup-1').one()
        self.assertEqual(pay.user_id, 101)
        self.assertEqual(pay.amount_cents, 10000)
        self.assertEqual(pay.status, 'success')

    def test_duplicate_callback_and_webhook_protection(self):
        """Verify duplicate Paystack callback/webhook with same reference cannot credit tokens twice."""
        tx = self.paystack_tx(reference='ref-dup-1', subject='budget_topup', tokens=100)
        with self.app.app_context():
            with patch('app.payments.paystack.db', SimpleNamespace(session=self.sessions)):
                with patch('app.payments.paystack.User', self.User):
                    with patch('app.payments.paystack.PaystackPayment', self.Payment):
                        with patch('app.models.auth.AitTokenWallet', self.Wallet):
                            with patch('app.models.auth.AitTokenTransaction', self.TokenTxn):
                                # First fulfillment
                                r1 = paystack_module.fulfill_order('tester@example.com', 'budget_topup', tx)
                                self.assertTrue(r1)
                                # Duplicate second callback/webhook
                                r2 = paystack_module.fulfill_order('tester@example.com', 'budget_topup', tx)
                                self.assertFalse(r2)
                                # Third duplicate
                                r3 = paystack_module.fulfill_order('tester@example.com', 'budget_topup', tx)
                                self.assertFalse(r3)

        # Wallet must only be credited once (100 -> 200, not 400)
        wallet = self.sessions.query(self.Wallet).filter_by(user_id=101).one()
        self.assertEqual(wallet.balance, 200)
        self.assertEqual(self.sessions.query(self.TokenTxn).count(), 1)
        self.assertEqual(self.sessions.query(self.Payment).count(), 1)

    def test_failed_and_abandoned_payment_handling(self):
        """Verify failed or abandoned Paystack transactions are rejected and allocate no tokens."""
        for bad_status in ['failed', 'abandoned', 'reversed']:
            tx = self.paystack_tx(reference=f'ref-bad-{bad_status}', subject='budget_topup', status=bad_status)
            with self.app.app_context():
                with patch('app.payments.paystack.db', SimpleNamespace(session=self.sessions)):
                    with self.assertRaises(ValueError):
                        paystack_module.fulfill_order('tester@example.com', 'budget_topup', tx)

        # Balance remains unaffected at 100
        wallet = self.sessions.query(self.Wallet).filter_by(user_id=101).one()
        self.assertEqual(wallet.balance, 100)
        self.assertEqual(self.sessions.query(self.Payment).count(), 0)

    def test_tampered_order_and_unauthorized_token_prevention(self):
        """Verify tampered token counts, amounts, or references are rejected before database writes."""
        with self.app.app_context():
            base_tx = self.paystack_tx(reference='ref-tamper-1', subject='budget_topup', tokens=100)

            # Attack 1: Attacker changes token count in metadata
            tampered_tokens = deepcopy(base_tx)
            tampered_tokens['metadata']['tokens_purchased'] = 50000
            with patch('requests.get', return_value=self.mock_paystack_response(tampered_tokens)):
                with self.assertRaises(ValueError):
                    security.verified_transaction('ref-tamper-1', self.secret)

            # Attack 2: Attacker changes amount
            tampered_amount = deepcopy(base_tx)
            tampered_amount['amount'] = 100  # R1 instead of R100
            with patch('requests.get', return_value=self.mock_paystack_response(tampered_amount)):
                with self.assertRaises(ValueError):
                    security.verified_transaction('ref-tamper-1', self.secret)

            # Attack 3: Missing order signature
            tampered_sig = deepcopy(base_tx)
            tampered_sig['metadata']['order_token'] = 'invalid-forged-token'
            with patch('requests.get', return_value=self.mock_paystack_response(tampered_sig)):
                with self.assertRaises(ValueError):
                    security.verified_transaction('ref-tamper-1', self.secret)

        # No records written
        self.assertEqual(self.sessions.query(self.Payment).count(), 0)
        self.assertEqual(self.sessions.query(self.Wallet).filter_by(user_id=101).one().balance, 100)

