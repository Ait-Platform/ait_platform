    def render_legacy(self,template,**context):
        self.rendered=context
        return repr(context)
    def payment_state(self):
        return {t:list(self.session.execute(text('SELECT * FROM '+t+' ORDER BY id'))) for t in ('bil_muni_payment','bil_metsoa_cycle','bil_muni_cycle_totals','bil_meter_reading','bil_consumption')}
    def test_same_number_payments_are_written_only_to_each_users_own_account(self):
        for user,account in [(7,1),(8,90)]:
            self.user.id=user
            response=self.capture_post('/legacy/muni_payment_submit',account_number='MET-26',date='2025-10-01',amount='10',metro_due='20',metsoa='30',request_key=str(uuid.uuid4()))
            self.assertEqual(response.status_code,302,response.text)
            self.assertEqual(self.session.execute(text('SELECT amount FROM bil_muni_payment WHERE account_id=:a'),dict(a=account)).scalar(),10)
        self.user.id=7
        self.assertEqual(self.capture_post('/legacy/muni_payment_delete',account_number='MET-26',month='2025-10').status_code,302)
        self.assertEqual(self.session.execute(text('SELECT count(*) FROM bil_muni_payment WHERE account_id=90')).scalar(),1)
        self.assertEqual(self.session.execute(text('SELECT count(*) FROM bil_muni_payment WHERE account_id=1')).scalar(),1)
    def test_legacy_property_view_and_editor_are_reachable_without_undefined_context(self):
        self.app._got_first_request=False
        self.app.add_url_rule('/safe-property/<int:property_id>',endpoint='billing_bp.property_edit',view_func=lambda **kw:'Property editor')
        page=self.client.get('/legacy/view_property/26',headers=self.headers)
        self.assertEqual(page.status_code,200,page.text)
        page=self.client.get('/legacy/edit_property/26',headers=self.headers)
        self.assertEqual(page.status_code,303,page.text)
        self.assertTrue(page.location.endswith('/safe-property/26'))
        self.assertEqual(self.client.get('/legacy/edit_property/28',headers=self.headers).status_code,403)

    def test_legacy_payment_retries_append_and_deletion_preserves_evidence(self):
        fields=dict(account_number='MET-26',date='2025-10-01',amount='10',request_key=str(uuid.uuid4()))
        self.assertEqual(self.capture_post('/legacy/muni_payment_submit',**fields).status_code,302)
        self.assertEqual(self.capture_post('/legacy/muni_payment_submit',**fields).status_code,302)
        self.assertEqual(self.capture_post('/legacy/muni_payment_submit',**dict(fields,request_key=str(uuid.uuid4()))).status_code,302)
        before=self.payment_state()
        self.assertEqual(self.capture_post('/legacy/muni_payment_delete',account_number='MET-26',month='2025-10').status_code,302)
        self.assertEqual(before,self.payment_state())
        self.assertEqual(self.session.execute(text('SELECT count(*) FROM bil_muni_payment WHERE account_id=1')).scalar(),2)
        self.assertEqual(self.session.execute(text("SELECT count(*) FROM bil_utilities_capture_audit WHERE kind='municipal_payment'")).scalar(),2)

    def test_foreign_number_or_property_cannot_read_write_delete_or_send_email(self):
        before=self.payment_state()
        for name in ('muni_payment_submit','muni_payment_delete','muni_recon_edit','muni_recon_email','muni_recon_email_send'):
            fields=dict(account_number='PRIVATE-ONLY',month='2025-10',date='2025-10-01',amount='10',to_email='nobody@example.com',subject='test',body_text='test')
            response=self.capture_post('/legacy/'+name,**fields) if name in ('muni_payment_submit','muni_payment_delete','muni_recon_email_send') else self.client.get('/legacy/'+name,query_string=fields,headers=self.headers)
            self.assertEqual(response.status_code,404,(name,response.text))
        response=self.capture_post('/legacy/muni_payment_submit',account_number='MET-26',property_id='28',date='2025-10-01',amount='10')
        self.assertEqual(response.status_code,403);self.assertEqual(before,self.payment_state());self.mail.assert_not_called()
    def test_email_selection_and_meter_fallback_do_not_include_foreign_records(self):
        response=self.client.get('/legacy/muni_recon_email',headers=self.headers)
        self.assertNotIn('PRIVATE-ONLY',response.text)
        response=self.client.get('/legacy/muni_recon_email?account_number=MET-26&month=2026-10',headers=self.headers)
        self.assertEqual(response.status_code,200,response.text)
        self.session.execute(text("UPDATE bil_meter SET meter_number='FOREIGN METER' WHERE id=90"));self.session.commit();self.conn.commit()
        response=self.client.get('/legacy/muni_recon_email?account_number=MET-26&month=2026-10',headers=self.headers)
        self.assertNotIn('FOREIGN METER',response.text)
    def test_reconciliation_aggregates_only_selected_owned_property(self):
        self.session.execute(text('UPDATE bil_tenant SET property_id=26 WHERE id=11'))
        self.session.execute(text("INSERT INTO bil_tenant_ledger VALUES(1,11,'2025-10',20,'METSOA-AUTO'),(2,99,'2025-10',999,'METSOA-AUTO')"));self.session.commit();self.conn.commit()
        response=self.client.get('/legacy/muni_recon_statement?account_number=MET-26',headers=self.headers)
        self.assertEqual(response.status_code,200,response.text)
        self.assertEqual(self.rendered['rows'][0]['metsoa_charges'],20)
        self.assertNotIn('PRIVATE-ONLY',response.text)
        response=self.client.get('/legacy/muni_recon_edit?account_number=MET-26&month=2025-10',headers=self.headers)
        self.assertEqual(response.status_code,200,response.text);self.assertEqual(self.rendered['metsoa_charges'],20)
        self.assertEqual(self.client.get('/legacy/muni_recon_statement?account_number=PRIVATE-ONLY',headers=self.headers).status_code,404)
    def test_legacy_consumption_rebuild_cannot_delete_foreign_month(self):
        self.session.execute(text("INSERT INTO bil_consumption(id,meter_id,meter_number,month,consumption) VALUES(900,90,'WATER-26','2025-11',777)"));self.session.commit();self.conn.commit()
        before=list(self.session.execute(text('SELECT * FROM bil_consumption WHERE meter_id=90')))
        with patch('builtins.print'),self.app.test_request_context():self.legacy_env['generate_consumption_records_from_readings']('2025-11')
        self.assertEqual(before,list(self.session.execute(text('SELECT * FROM bil_consumption WHERE meter_id=90'))))
    def test_admin_claim_cannot_bypass_property_tenant_or_setup_scope_and_global_wipe_is_blocked(self):
        self.user.has_role=lambda role:True;before=self.payment_state()
        for name in ('delete_property','view_property','edit_property'):
            response=self.client.get('/legacy/'+name+'/28',headers=self.headers);self.assertEqual(response.status_code,403,name)
        self.assertEqual(self.client.get('/legacy/tenant_mapping/99',headers=self.headers).status_code,403)
        self.assertEqual(self.client.get('/legacy/setup_property/8',headers=self.headers).status_code,403)
        self.assertEqual(self.capture_post('/legacy/wipe_tables').status_code,403)
        self.assertEqual(self.client.get('/legacy/tenant_mapping/99').status_code,403)
        self.assertEqual(before,self.payment_state())

