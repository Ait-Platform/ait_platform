"""Rehearse the configured Alembic entry point on disposable local PostgreSQL."""
import os
from pathlib import Path
import subprocess
import sys
import unittest

ROOT=Path(__file__).resolve().parents[1]

class PMMigrationCommandTests(unittest.TestCase):
    def test_targeted_upgrade_uses_real_environment_preserves_heads_and_rows(self):
        code = r'''
import os
from pathlib import Path
from dotenv import dotenv_values
from sqlalchemy import create_engine,text
from sqlalchemy.engine import make_url
from alembic import command
from alembic.config import Config
from alembic.script import ScriptDirectory
root=Path.cwd()
raw=dotenv_values(root.parents[1]/'.env').get('DATABASE_URL','')
target=make_url(raw)
assert target.get_backend_name()=='postgresql'
assert target.database=='ait_local_db' and target.host in ('localhost','127.0.0.1','::1')
os.environ['DATABASE_URL']=raw
# Import definitions only, then prove Alembic never invokes the application factory.
import app
def forbidden_factory(*a,**kw):raise AssertionError('Application startup is forbidden for migration rehearsal')
app.create_app=forbidden_factory
config=Config(str(root/'alembic.ini'))
script=ScriptDirectory.from_config(config)
existing=set(script.get_heads())-{'pm_soa_001'}
assert script.get_revision('pm_soa_001').down_revision is None
engine=create_engine(target)
with engine.connect() as c:
    c.execute(text('SET search_path TO pg_temp'))
    c.execute(text("""CREATE TEMP TABLE bil_tenant_ledger(
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        tenant_id integer NOT NULL,txn_date timestamp,month varchar(7),
        description varchar(255),kind varchar(50),amount numeric(10,2),ref varchar(255))"""))
    c.execute(text("CREATE TEMP TABLE alembic_version(version_num varchar(32) NOT NULL PRIMARY KEY)"))
    for revision in existing:c.execute(text('INSERT INTO alembic_version VALUES(:v)'),dict(v=revision))
    c.execute(text("""INSERT INTO bil_tenant_ledger(tenant_id,description,kind,amount,ref)
        VALUES(11,'Historical charge','charge',100,'D0042'),(11,'Historical payment','payment',-5,'C0007')"""))
    before=c.execute(text('SELECT * FROM bil_tenant_ledger ORDER BY id')).all()
    c.commit()
    config.attributes['connection']=c
    command.upgrade(config,'pm_soa_001')
    after=c.execute(text('SELECT id,tenant_id,txn_date,month,description,kind,amount,ref FROM bil_tenant_ledger ORDER BY id')).all()
    assert before==after
    assert set(c.execute(text('SELECT version_num FROM alembic_version')).scalars())==existing|{'pm_soa_001'}
    assert c.execute(text("SELECT last_value FROM pm_ledger_debit_ref_seq")).scalar()==42
    assert c.execute(text("SELECT last_value FROM pm_ledger_credit_ref_seq")).scalar()==7
    c.commit()
    command.upgrade(config,'pm_soa_001') # Alembic tracking makes a second invocation a no-op.
    assert c.execute(text('SELECT count(*) FROM bil_tenant_ledger')).scalar()==2
print('Targeted Alembic rehearsal passed; existing heads and financial rows preserved.')
'''
        result=subprocess.run([sys.executable,'-c',code],cwd=ROOT,capture_output=True,text=True,timeout=90)
        # Do not echo raw driver errors or connection strings on failure.
        self.assertEqual(result.returncode,0,
            'Isolated Alembic rehearsal failed. Inspect sanitized local error categories.')
        self.assertIn('Targeted Alembic rehearsal passed',result.stdout)
