    def snapshot(self):
        return {table:self.session.execute(text('SELECT * FROM '+table+' ORDER BY id')).mappings().all() for table in ('bil_muni_account','bil_meter','bil_meter_reading','bil_consumption','bil_architecture_draft')}
    def test_setup_button_reuses_selected_property_and_original_wizard(self):
        before=self.snapshot()
        hub=self.client.get('/soa-test/utilities_hub',headers=self.headers)
        self.assertEqual(hub.status_code,200,hub.text)
        tree=html.fromstring(hub.data)
        button=tree.xpath('//button[@name="action"][@value="setup"]')[0]
        self.assertEqual(button.text_content(),'Setup Wizard')
        response=self.client.post('/soa-test/utilities_hub',data=dict(csrf_token=self.csrf,action='setup',property_id='26'),headers=self.headers)
        self.assertEqual(response.status_code,302);self.assertTrue(response.location.startswith('/billing/setup?property_id=26&billing_month='))
        page=self.client.get(response.location,headers=self.headers)
        self.assertEqual(page.status_code,200,page.text)
        self.assertIn('Architecture Mapping',page.text);self.assertIn('MET-26',page.text)
        self.assertTrue(html.fromstring(page.data).xpath('//*[@id="setup-read-only-notice"]'))
        self.assertTrue(html.fromstring(page.data).xpath('//button[@id="btn-save"][@disabled]'))
        self.assertIn('const SETUP_READ_ONLY = true;',page.text)
        self.assertEqual(self.snapshot(),before)
    def test_all_existing_configuration_save_paths_are_blocked_without_any_history_changes(self):
        before=self.snapshot();writes=[]
        def capture(conn,cursor,sql,params,context,many):
            if sql.lstrip().lower().startswith(('delete ','update ','insert ')):writes.append(sql)
        event.listen(self.conn,'before_cursor_execute',capture)
        try:
            for path in ('/save_architecture_draft/26','/billing/onboarding/save_global_architecture/26','/billing/onboarding/process'):
                response=self.client.post(path,json=dict(property_id=26,accounts=[]),headers=dict(self.headers,**{'X-CSRFToken':self.csrf}))
                self.assertEqual(response.status_code,409,response.text);self.assertTrue('view-only' in response.text or 'Legacy tenant/unit onboarding is disabled' in response.text)
            parse=self.client.post('/api/parse_bill_onboarding',data=dict(property_id=26,csrf_token=self.csrf),headers=self.headers)
            self.assertEqual(parse.status_code,409)
            legacy=self.client.post('/billing/setup/submit',data=dict(csrf_token=self.csrf,payload=json.dumps({'property_id':26})),headers=self.headers)
            self.assertEqual(legacy.status_code,409)
        finally:event.remove(self.conn,'before_cursor_execute',capture)
        self.assertFalse(writes);self.assertEqual(self.snapshot(),before)
    def test_ownership_csrf_and_direct_urls_remain_enforced(self):
        self.assertEqual(self.client.get('/billing/setup?property_id=28',headers=self.headers).status_code,403)
        self.assertEqual(self.client.get('/billing/setup?property_id=26').status_code,403)
        response=self.client.post('/soa-test/utilities_hub',data=dict(csrf_token=self.csrf,action='setup',property_id=28),headers=self.headers)
        self.assertEqual(response.status_code,403)
        for path in ('/save_architecture_draft/28','/billing/onboarding/save_global_architecture/28'):
            self.assertEqual(self.client.post(path,json={},headers=dict(self.headers,**{'X-CSRFToken':self.csrf})).status_code,403)
        self.assertEqual(self.client.post('/save_architecture_draft/26',json={ },headers=self.headers).status_code,400)
    def test_initial_draft_save_allowed_but_existing_account_or_meter_identity_not_claimed(self):
        response=self.client.post('/save_architecture_draft/27',json={'accounts':[{'number':'NEW-27'}]},headers=dict(self.headers,**{'X-CSRFToken':self.csrf}))
        self.assertEqual(response.status_code,200,response.text)
        self.assertEqual(self.session.execute(text('SELECT count(*) FROM bil_muni_account')).scalar(),1)
        for proposed in ({'accounts':[{'number':'MET-26'}]},{'subWater':[{'number':'WATER-26'}]}):
            response=self.client.post('/billing/onboarding/save_global_architecture/27',json=proposed,headers=dict(self.headers,**{'X-CSRFToken':self.csrf}))
            self.assertEqual(response.status_code,409,response.text)
        self.assertEqual(self.session.execute(text('SELECT count(*) FROM bil_meter_reading')).scalar(),1)

