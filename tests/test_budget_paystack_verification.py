    def test_webhook_hmac_signature_verification_and_rejection(self):
        """Verify webhook accepts valid HMAC-SHA512 signatures and rejects forged or unsigned calls."""
        blueprint = Blueprint('paystack_bp_test', __name__)
        blueprint.add_url_rule('/webhook', 'paystack_webhook', paystack_module.webhook, methods=['POST'])
        self.app.register_blueprint(blueprint)

        tx = self.paystack_tx(reference='ref-wh-1', subject='budget_topup', tokens=100)
        body = json.dumps({'event': 'charge.success', 'data': tx}).encode('utf-8')
        valid_sig = hmac.new(self.secret.encode('utf-8'), body, hashlib.sha512).hexdigest()

        with patch('app.payments.paystack.get_paystack_secret', return_value=self.secret):
            with patch('app.payments.paystack.db', SimpleNamespace(session=self.sessions)):
                with patch('app.payments.paystack.User', self.User):
                    with patch('app.payments.paystack.PaystackPayment', self.Payment):
                        with patch('app.models.auth.AitTokenWallet', self.Wallet):
                            with patch('app.models.auth.AitTokenTransaction', self.TokenTxn):
                                with patch('requests.get', return_value=self.mock_paystack_response(tx)):
                                    # 1. Invalid signature must return 401
                                    r_bad = self.client.post('/webhook', data=body, content_type='application/json', headers={'x-paystack-signature': 'bad-sig'})
                                    self.assertEqual(r_bad.status_code, 401)
                                    self.assertEqual(self.sessions.query(self.Wallet).filter_by(user_id=101).one().balance, 100)

                                    # 2. Valid signature must return 200 and fulfill
                                    r_ok = self.client.post('/webhook', data=body, content_type='application/json', headers={'x-paystack-signature': valid_sig})
                                    self.assertEqual(r_ok.status_code, 200)
                                    self.assertEqual(self.sessions.query(self.Wallet).filter_by(user_id=101).one().balance, 200)

                                    # 3. Replay webhook must return 200 and NOT credit again
                                    r_replay = self.client.post('/webhook', data=body, content_type='application/json', headers={'x-paystack-signature': valid_sig})
                                    self.assertEqual(r_replay.status_code, 200)
                                    self.assertEqual(self.sessions.query(self.Wallet).filter_by(user_id=101).one().balance, 200)

