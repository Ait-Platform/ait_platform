    def test_budget_bridge_status_displays_active_and_dynamic_wallet_balance(self):
        """Bridge must display BudgetCash — Active | Wallet: XXX tokens with actual balance."""
        with self.client.session_transaction() as sess:
            sess['_user_id'] = str(self.user_id)

        # Initial balance is 100
        res = self.client.get('/bridge')
        self.assertEqual(res.status_code, 200)
        content = res.get_data(as_text=True)
        self.assertIn("BudgetCash — Active | Wallet: 100 tokens", content)
        self.assertNotIn("Your trial/subscription program is active.", content)

        # Dynamically change balance to 150
        self.conn.execute(sa.text("UPDATE ait_token_wallet SET balance=150 WHERE user_id=:uid"), {'uid': self.user_id})
        self.session.expire_all()

        res2 = self.client.get('/bridge')
        self.assertEqual(res2.status_code, 200)
        content2 = res2.get_data(as_text=True)
        self.assertIn("BudgetCash — Active | Wallet: 150 tokens", content2)

