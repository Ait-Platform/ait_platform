    def test_paystack_topup_50_tokens_fulfillment_and_idempotency(self):
        """Test R50 Paystack payment fulfilling 50 tokens to BudgetCash wallet exactly once."""
        paystack_mod = load('app.payments.paystack', 'app/payments/paystack.py')

        user = self.User.query.get(self.user_id)
        wallet = self.AitTokenWallet.query.filter_by(user_id=self.user_id).first()
        initial_balance = wallet.balance

        # Mock transaction for R50 (5000 cents) = 50 tokens
        tx = {
            'status': 'success',
            'reference': 'ref-bc-r50-live',
            'amount': 5000,
            'currency': 'ZAR',
            'metadata': {'tokens_purchased': 50}
        }

        # Fulfill order
        result = paystack_mod.fulfill_order(user.email, 'budget_topup', tx)
        self.assertTrue(result)

        self.session.expire_all()
        updated_wallet = self.AitTokenWallet.query.filter_by(user_id=self.user_id).first()
        self.assertEqual(updated_wallet.balance, initial_balance + 50)

        # Check transaction record
        tx_record = self.AitTokenTransaction.query.filter_by(wallet_id=wallet.id).order_by(self.AitTokenTransaction.id.desc()).first()
        self.assertEqual(tx_record.amount, 50)
        self.assertIn("Paystack Top-Up (Budget)", tx_record.description)

        # Duplicate replay attempt
        dup_result = paystack_mod.fulfill_order(user.email, 'budget_topup', tx)
        self.assertFalse(dup_result)

        # Balance remains unchanged after replay
        self.session.expire_all()
        wallet_after_dup = self.AitTokenWallet.query.filter_by(user_id=self.user_id).first()
        self.assertEqual(wallet_after_dup.balance, initial_balance + 50)


