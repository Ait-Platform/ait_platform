        self.assertEqual(html.fromstring(conflict.data).xpath('//input[@name="posting_key"]/@value'),[data['posting_key']])
        self.assertEqual(self.session.execute(text('SELECT count(*) FROM bil_tenant_ledger')).scalar(),1)
