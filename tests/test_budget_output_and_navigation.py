    def test_output_email_dispatch_and_duplicate_prevention(self):
        """Email dispatch sends PDF attachment and prevents duplicate submissions."""
        self.login()

        prev_res = self.client.get('/budget/output?report_type=statement&preview=1&date_from=2026-11-01&date_to=2026-11-30')
        token_prefix = 'preview_token='
        raw_token = prev_res.get_data(as_text=True).split(token_prefix)[1].split('&')[0].split('"')[0]

        sent_messages = []

        def mock_send_pdf_email(**kwargs):
            sent_messages.append(kwargs)

        with patch('app.utils.mailer.send_pdf_email', side_effect=mock_send_pdf_email):
            # First send
            post_data = {
                'action': 'email',
                'preview_token': raw_token,
                'report_type': 'statement',
                'account_id': '',
                'date_from': '2026-11-01',
                'date_to': '2026-11-30',
                'email_to': 'recipient@example.com',
            }
            res = self.client.post('/budget/output', data=post_data)
            self.assertEqual(res.status_code, 200)
            self.assertEqual(len(sent_messages), 1)
            self.assertEqual(sent_messages[0]['to_email'], 'recipient@example.com')
            self.assertTrue(sent_messages[0]['pdf_bytes'].startswith(b'%PDF-'))

            # Duplicate send with same token and email
            dup_res = self.client.post('/budget/output', data=post_data)
            self.assertEqual(dup_res.status_code, 409)
            # No second email sent
            self.assertEqual(len(sent_messages), 1)

