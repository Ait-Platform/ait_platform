    def login(self, uid):
        with self.client.session_transaction() as values:
            values.clear()
            if uid:
                values['_user_id'] = str(uid)
                values['_fresh'] = True

    def account(self, name, kind='expense', owner=None):
        owner = owner or self.user_id
        row = self.session.execute(sa.text('INSERT INTO bud_account(user_id,code,name,kind) VALUES (:u,:code,:n,:k) RETURNING id'), {'u': owner, 'code': re.sub('[^a-z0-9]', '-', name.lower()), 'n': name, 'k': kind}).scalar_one()
        self.session.commit()
        return row

    def add(self, aid, amount, day='2026-11-10'):
        return self.client.post('/budget/ledger/add', data={'account_id': str(aid), 'txn_date': day, 'amount': amount})

