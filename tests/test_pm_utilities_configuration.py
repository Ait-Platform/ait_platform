"""Property-only configuration saves on isolated PostgreSQL fixtures."""
import copy
from sqlalchemy import text
from flask import Flask
import test_pm_metsoa_setup_safety as fixture

class UtilitiesConfigurationTests(fixture.MetsoaSetupProtectionTests):
    def setUp(self):
        super().setUp()
        for table in ('bil_meter','bil_muni_account','ref_muni_owner'):
            self.session.execute(text('ALTER TABLE '+table+' ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 1000)'))
        self.session.execute(text('ALTER TABLE ref_muni_owner ADD UNIQUE(name)'));self.session.commit();self.conn.commit()
    def payload(self,p=26):
        from app.program_billing.utilities_configuration import revision
        with self.app.app_context():version=revision(p)
        return dict(mode='property_configuration_v1',configuration_revision=version,accounts=[dict(id='acc_0',record_id=1,number='MET-26',isBulk=False)],subWater=[dict(id='sub-water_0',record_id=1,number='WATER-26')],mapping=[dict(account_id='acc_0',water='sub-water_0')],owners=[dict(account_id='acc_0',name='Owner',email='owner@example.com',address='Address')])
    def save(self,data,p=26):
        return self.client.post('/billing/onboarding/save_global_architecture/'+str(p),json=data,headers=dict(self.headers,**{'X-CSRFToken':self.csrf}))
    def test_safe_edit_keeps_stable_ids_and_all_history(self):
        before=self.snapshot();payload=self.payload();response=self.save(payload)
        self.assertEqual(response.status_code,200,response.text)
        after=self.snapshot()
        for table in ('bil_meter','bil_meter_reading','bil_consumption','bil_architecture_draft'):self.assertEqual(before[table],after[table])
        self.assertEqual(after['bil_muni_account'][0]['id'],1)
        self.assertEqual(after['bil_muni_account'][0]['muni_email'],'owner@example.com')
        self.assertEqual(self.save(payload).status_code,409)
        page=self.client.get('/billing/setup?property_id=26&edit=1',headers=self.headers)
        self.assertEqual(page.status_code,200,page.text)
        self.assertIn('const SETUP_READ_ONLY = false',page.text)
        self.assertIn('"record_id": 1',page.text)
    def test_new_accounts_and_both_meter_types_use_property_only(self):
        payload=self.payload(27)
        payload.update(accounts=[dict(id='a',number='NEW-27')],subWater=[dict(id='w',number='NEW-W')],subElec=[dict(id='e',number='NEW-E')],mapping=[dict(account_id='a',water='w',elec='e')],owners=[])
        self.assertEqual(self.save(payload,27).status_code,200)
        rows=self.session.execute(text('SELECT property_id,utility_type FROM bil_meter WHERE property_id=27')).all()
        self.assertEqual(set(rows),{(27,'Water'),(27,'Electrical')})
        self.assertEqual(self.session.execute(text('SELECT count(*) FROM bil_meter_reading')).scalar(),1)
    def test_cannot_claim_unassociated_account_or_other_property_ids(self):
        before=self.snapshot();payload=self.payload();payload['accounts'][0]['record_id']=999
        self.assertEqual(self.save(payload).status_code,403);self.assertEqual(before,self.snapshot())
        self.session.execute(text("INSERT INTO bil_muni_account(account_number) VALUES('UNLINKED')"));self.session.commit()
        payload=self.payload(27);payload.update(accounts=[dict(id='a',number='UNLINKED')],subWater=[],mapping=[],owners=[])
        self.assertEqual(self.save(payload,27).status_code,409)
        self.assertEqual(self.session.execute(text("SELECT property_id FROM bil_muni_account WHERE account_number='UNLINKED'")).scalar(),None)
    def test_omission_or_renumbering_cannot_replace_existing_records(self):
        before=self.snapshot();payload=self.payload();payload['subWater']=[]
        self.assertEqual(self.save(payload).status_code,409);self.assertEqual(before,self.snapshot())
        payload=self.payload();payload['subWater'][0]['number']='CHANGED'
        self.assertEqual(self.save(payload).status_code,409);self.assertEqual(before,self.snapshot())

    def test_five_individual_water_meters_use_bulk_parent_without_electricity_bulk(self):
        payload=self.payload(27)
        payload.update(accounts=[dict(id='bulk',number='BULK-27',isBulk=True)]+[dict(id='a'+str(i),number='ACCOUNT-'+str(i)) for i in range(5)],bulkWater=[dict(id='bw',number='BULK-W')],subWater=[dict(id='w'+str(i),number='W-'+str(i),parent_id='bw') for i in range(5)],subElec=[dict(id='e',number='E-27')],mapping=[dict(account_id='a'+str(i),water='w'+str(i),elec='e' if i==0 else '') for i in range(5)],owners=[])
        response=self.save(payload,27);self.assertEqual(response.status_code,200,response.text)
        bulk=self.session.execute(text("SELECT id FROM bil_meter WHERE meter_number='BULK-W'")).scalar()
        self.assertEqual(self.session.execute(text('SELECT count(*) FROM bil_meter WHERE parent_meter_id=:p'),dict(p=bulk)).scalar(),5)
        self.assertIsNone(self.session.execute(text("SELECT parent_meter_id FROM bil_meter WHERE meter_number='E-27'")).scalar())
        self.assertEqual(self.session.execute(text('SELECT count(*) FROM bil_meter_reading')).scalar(),1)
    def test_circular_or_cross_property_bulk_reference_rolls_back_every_change(self):
        payload=self.payload(27)
        payload.update(accounts=[dict(id='b',number='B-27',isBulk=True)],bulkWater=[dict(id='bw',number='BW-27',parent_id='bw')],subWater=[],mapping=[],owners=[])
        before=self.snapshot();self.assertEqual(self.save(payload,27).status_code,400);self.assertEqual(before,self.snapshot())
        payload['bulkWater'][0]['parent_id']='sub-water_0'
        self.assertEqual(self.save(payload,27).status_code,400);self.assertEqual(before,self.snapshot())
