    def test_independent_sessions_cannot_duplicate_simultaneous_payments(self):
        import ast,re,types
        from sqlalchemy import inspect
        from sqlalchemy.orm import Session
        from threading import Barrier
        from concurrent.futures import ThreadPoolExecutor
        from werkzeug.exceptions import HTTPException
        from flask import abort
        import test_pm_admin_landing as loader
        prefix='pm_recon_pay_test_'+uuid.uuid4().hex+'_'
        names=('bil_property','bil_muni_account','bil_municipal_statement','bil_muni_payment','bil_utilities_capture_audit')
        tables={name:prefix+'t'+str(i) for i,name in enumerate(names)}
        for name,target in tables.items():
            self.assertRegex(target,r'^pm_recon_pay_test_[a-f0-9]{32}_t[0-9]+$')
            self.session.execute(text('CREATE TABLE public.'+target+' (LIKE '+name+' INCLUDING CONSTRAINTS)'))
            self.session.execute(text('INSERT INTO public.'+target+' SELECT * FROM '+name))
        for name in ('bil_muni_payment','bil_utilities_capture_audit'):
            self.session.execute(text('ALTER TABLE public.'+tables[name]+' ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 1000)'))
        self.session.execute(text('ALTER TABLE public.'+tables['bil_utilities_capture_audit']+' ALTER COLUMN recorded_at SET DEFAULT now()'))
        self.session.commit();self.conn.commit()
        def cleanup():
            self.session.rollback();self.conn.rollback()
            self.assertEqual(self.conn.execute(text('SELECT current_database()')).scalar(),'ait_local_db')
            for table in reversed(list(tables.values())):self.conn.execute(text('DROP TABLE public.'+table))
            self.conn.commit()
        self.addCleanup(cleanup)
        source=ast.parse(Path('app/program_billing/utilities_capture.py').read_text())
        source.body=[n for n in source.body if not (isinstance(n,ast.ImportFrom) and ((n.module or '').startswith('app.') or n.level))]
        pattern=re.compile(r'\b('+'|'.join(tables)+r')\b')
        def concurrent(forms):
            barrier=Barrier(len(forms))
            def save(form):
                with self.engine.connect() as connection:
                    with Session(connection) as session:
                        service=types.ModuleType('concurrent_reconciliation_payments')
                        service.db=types.SimpleNamespace(session=session)
                        exec(compile(source,'utilities_capture.py','exec'),service.__dict__)
                        service.current_user=types.SimpleNamespace(id=7)
                        service.text=lambda sql:text(pattern.sub(lambda m:'public.'+tables[m.group(0)],sql))
                        def available(table,columns):
                            target=tables[table];catalog=inspect(connection)
                            return catalog.has_table(target,schema='public') and set(columns)<={c['name'] for c in catalog.get_columns(target,schema='public')}
                        service.available=available
                        service.property_scope=loader.function('app/program_billing/metsoa_setup_safety.py','property_scope',dict(db=service.db,current_user=service.current_user,text=service.text,abort=abort))
                        barrier.wait(timeout=10)
                        try:
                            result=service.record_payment(26,form);session.commit();connection.commit()
                            return result[0]
                        except HTTPException as exc:
                            session.rollback();connection.rollback();return -exc.code
            with ThreadPoolExecutor(max_workers=len(forms)) as pool:return list(pool.map(save,forms))
        form=dict(statement_id=str(self.statement['id']),request_key=str(uuid.uuid4()),payment_date='2026-10-15',payment_amount='30.00',payment_reference='CONCURRENT-RETRY')
        results=concurrent([form,form])
        self.assertEqual(results[0],results[1]);self.assertGreater(results[0],0)
        first=dict(form,request_key=str(uuid.uuid4()),payment_reference='CONCURRENT-FRESH')
        second=dict(first,request_key=str(uuid.uuid4()))
        results=concurrent([first,second])
        self.assertEqual(sum(r>0 for r in results),1);self.assertIn(-409,results)
        count=self.session.execute(text('SELECT count(*) FROM public.'+tables['bil_muni_payment']+" WHERE reference LIKE 'CONCURRENT-%'")).scalar()
        self.assertEqual(count,2)

    def test_browser_record_payment_alongside_edit_and_refresh(self):
        from playwright.sync_api import sync_playwright
        from http.server import HTTPServer,BaseHTTPRequestHandler
        from threading import Thread
        case=self
        class Handler(BaseHTTPRequestHandler):
            def log_message(self,*args):pass
            def do_GET(self):self.respond(case.client.get(self.path,headers=case.headers))
            def do_POST(self):
                payload=self.rfile.read(int(self.headers['Content-Length']))
                self.respond(case.client.post(self.path,data=payload,content_type=self.headers.get('Content-Type'),headers=case.headers))
            def respond(self,response):
                self.send_response(response.status_code);self.send_header('Content-Type',response.content_type)
                if response.location:self.send_header('Location',response.location)
                self.end_headers();self.wfile.write(response.data);response.close()
        server=HTTPServer(('127.0.0.1',0),Handler);thread=Thread(target=server.serve_forever,daemon=True);thread.start()
        self.addCleanup(lambda:(server.shutdown(),server.server_close(),thread.join(timeout=2)))
        with sync_playwright() as runtime:
            browser=runtime.chromium.launch(headless=True)
            try:
                page=browser.new_page();page.goto('http://127.0.0.1:'+str(server.server_port)+self.statements_url)
                row=page.locator('tr[data-statement-row]').filter(has=page.get_by_role('link',name='Record Payment',exact=True)).filter(has_text='2026-09-28').first
                self.assertEqual(row.get_by_role('link',name='Edit',exact=True).count(),1)
                row.get_by_role('link',name='Record Payment',exact=True).click()
                form=page.locator('#municipal-payment-form')
                for key,value in dict(payment_date='2026-10-15',payment_amount='100.25',payment_reference='BROWSER-BANK').items():form.locator('[name="'+key+'"]').fill(value)
                form.get_by_role('button',name='Save Payment',exact=True).click()
                self.assertIn('R125.75',page.locator('tr[data-statement-row]').filter(has_text='2026-09-28').first.inner_text())
                page.reload()
                self.assertEqual(case.session.execute(text("SELECT count(*) FROM bil_muni_payment WHERE reference='BROWSER-BANK'")).scalar(),1)
            finally:browser.close()


